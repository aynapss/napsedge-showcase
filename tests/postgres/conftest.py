"""
Phase 5B7: shared fixtures for real, disposable-PostgreSQL integration
tests. Every fixture here is deliberately narrow and disposable:

- One PostgreSQL *container* (Docker, via `testcontainers`) is started
  once per test session, with randomly generated, throwaway credentials
  -- never a fixed default, never read from `.env`/`NAPSEDGE_DATABASE_URL`.
- Every individual TEST gets its own uniquely named, freshly created
  database on that one container, dropped again when the test ends
  (success or failure) -- tests never share mutable state through the
  database layer.
- `assert_disposable_database_name` is a standalone safety guard, used
  both operationally (before this module ever runs DDL against a name)
  and exercised directly by `test_postgres_safety.py` -- it refuses any
  database name that doesn't carry this batch's own test-only prefix, so
  a coding mistake that accidentally pointed at a real database name
  would fail loudly instead of silently proceeding.

If Docker is not running/available, every fixture here calls
`pytest.skip(...)` with a concise, specific diagnostic -- never a bare
collection error, and never a false claim that PostgreSQL was validated.
This module never touches `TeamDump`, never reads `.env`, and never binds
the disposable instance to anything beyond localhost (`testcontainers`'
default Docker port-publishing, reachable only from this host).
"""
from __future__ import annotations

import secrets
import shutil
import uuid
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, text

#: Every database this module creates carries this prefix -- the one and
#: only thing `assert_disposable_database_name` accepts. Never a real
#: project/production database name by construction (those never carry
#: this prefix and are never generated by this module).
TEST_DB_PREFIX = "napsedge_pg_test_"


def assert_disposable_database_name(name: str) -> None:
    """
    Refuse to operate (create, migrate, drop) on any database whose name
    does not clearly self-identify as this batch's own disposable test
    database. Raises `RuntimeError`, never silently proceeds.
    """
    if not name.startswith(TEST_DB_PREFIX):
        raise RuntimeError(
            f"refusing to run PostgreSQL integration setup against non-test "
            f"database name {name!r} -- expected a name starting with "
            f"{TEST_DB_PREFIX!r}. This guard exists so a coding mistake can "
            f"never point this batch's setup/teardown at a real database."
        )


def _docker_daemon_reachable() -> tuple[bool, str]:
    """Returns (available, diagnostic). Never raises -- always safe to call from a fixture."""
    if shutil.which("docker") is None:
        return False, "the `docker` CLI is not on PATH -- install Docker Desktop to run PostgreSQL integration tests."
    try:
        import docker as docker_sdk

        client = docker_sdk.from_env()
        client.ping()
        return True, ""
    except Exception as exc:  # pragma: no cover -- exact exception type varies by platform/daemon state
        return False, f"Docker is installed but its daemon is not reachable ({exc.__class__.__name__}: {exc}) -- start Docker Desktop and retry."


@pytest.fixture(scope="session")
def docker_available() -> None:
    ok, reason = _docker_daemon_reachable()
    if not ok:
        pytest.skip(f"PostgreSQL integration tests require a running Docker daemon: {reason}")


@pytest.fixture(scope="session")
def pg_container(docker_available):
    """
    One disposable PostgreSQL 16 container for the whole test session.
    Credentials and the container's own default database name are
    randomly generated here -- never a fixed/default value, never read
    from `.env` or `NAPSEDGE_DATABASE_URL`. Stopped (and, via the
    `testcontainers` Ryuk reaper, garbage-collected even on an abnormal
    exit) at the end of the session -- cleanup runs after both success
    and failure.
    """
    from testcontainers.community.postgres import PostgresContainer

    admin_user = f"pgtest_{secrets.token_hex(4)}"
    admin_password = secrets.token_urlsafe(24)
    admin_db = f"{TEST_DB_PREFIX}admin_{secrets.token_hex(4)}"
    assert_disposable_database_name(admin_db)

    container = PostgresContainer(
        "postgres:16-alpine",
        username=admin_user, password=admin_password, dbname=admin_db,
        driver="psycopg",
    )
    container.start()
    try:
        yield container
    finally:
        container.stop()


@pytest.fixture(scope="session")
def pg_version(pg_container) -> str:
    """
    Verifies the disposable instance genuinely identifies itself as
    PostgreSQL BEFORE any migration or behavioral test is allowed to run
    against it -- never assumed from the image tag alone.
    """
    engine = create_engine(pg_container.get_connection_url())
    try:
        with engine.connect() as conn:
            version = conn.execute(text("SELECT version()")).scalar()
    finally:
        engine.dispose()
    assert version and "PostgreSQL" in version, f"disposable instance does not identify as PostgreSQL: {version!r}"
    return version


@pytest.fixture()
def pg_empty_database_url(pg_container, pg_version) -> str:
    """
    Creates one uniquely named, empty database on the shared container for
    exactly one test, and drops it again when the test ends -- success or
    failure. The name is verified against `assert_disposable_database_name`
    before any DDL runs.
    """
    db_name = f"{TEST_DB_PREFIX}{uuid.uuid4().hex[:16]}"
    assert_disposable_database_name(db_name)

    admin_url = pg_container.get_connection_url()
    admin_engine = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    try:
        with admin_engine.connect() as conn:
            conn.execute(text(f'CREATE DATABASE "{db_name}"'))
    finally:
        admin_engine.dispose()

    base_url = admin_url.rsplit("/", 1)[0]
    test_url = f"{base_url}/{db_name}"

    try:
        yield test_url
    finally:
        assert_disposable_database_name(db_name)
        cleanup_engine = create_engine(admin_url, isolation_level="AUTOCOMMIT")
        try:
            with cleanup_engine.connect() as conn:
                conn.execute(text(
                    "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                    "WHERE datname = :db AND pid <> pg_backend_pid()"
                ), {"db": db_name})
                conn.execute(text(f'DROP DATABASE IF EXISTS "{db_name}"'))
        finally:
            cleanup_engine.dispose()


def alembic_config_for(url: str) -> Config:
    repo_root = Path(__file__).resolve().parents[2]
    cfg = Config(str(repo_root / "alembic.ini"))
    cfg.set_main_option("script_location", str(repo_root / "alembic"))
    cfg.set_main_option("sqlalchemy.url", url)
    return cfg


