"""
Phase 9B-8B: the BUILT backup image runs `backup-cycle` end to end -- its own `age` and pinned boto3, read-only root, uid 10001, no
socket -- capturing from the disposable cluster and storing an encrypted, read-back-verified copy in an S3 EMULATOR (moto's server, in a
container from the disposable test runner image; NOT Backblaze B2). The age key pair is generated by the image's own `age-keygen` into a
volume the backup container never mounts: only the PUBLIC recipients file is given to it. A separate retrieval (another container,
repository mounted read-only) then downloads, verifies and decrypts the copy with the separately held identity and reopens it through the
accepted verifier.

Runs only when `NAPSEDGE_BACKUP_IMAGE` (the built image) and `NAPSEDGE_TEST_RUNNER_IMAGE` (the 9B-8B runner, which carries moto) are set.
"""
from __future__ import annotations

import json
import os
import time
import uuid
from pathlib import Path

import pytest

from tests.postgres.test_postgres_backup_capture_lock import harness  # noqa: F401  (module fixture)
from tests.postgres.test_postgres_backup_capture_roundtrip import case  # noqa: F401  (fixture)
from tests.postgres.test_postgres_backup_image import CA_DIR, CRED_DIR, IMAGE, SCRATCH_DIR, STORE_DIR, docker, helper, job_env, put_password, volumes  # noqa: F401

RUNNER = os.environ.get("NAPSEDGE_TEST_RUNNER_IMAGE", "")
pytestmark = [pytest.mark.postgres, pytest.mark.skipif(not (IMAGE and RUNNER), reason="set NAPSEDGE_BACKUP_IMAGE and NAPSEDGE_TEST_RUNNER_IMAGE")]
LABEL = "org.napsedge.unit=9b8b"
STATE_DIR, RECIPIENTS_DIR = "/var/lib/napsedge-backup/state", "/run/napsedge-backup/recipients"
REPO = Path.cwd()


@pytest.fixture()
def emulator():
    name = f"napsedge-9b8b-moto-{uuid.uuid4().hex[:8]}"
    started = docker("run", "-d", "--name", name, "--label", LABEL, "--network", "bridge", "--entrypoint", "moto_server", RUNNER, "-H", "0.0.0.0", "-p", "5000")
    assert started.returncode == 0, started.stderr[-400:]
    try:
        ip = json.loads(docker("inspect", name, "--format", "{{json .NetworkSettings.Networks}}").stdout)["bridge"]["IPAddress"]
        endpoint, bucket = f"http://{ip}:5000", f"napsedge-image-{uuid.uuid4().hex[:10]}"
        script = ("import boto3,time\nfor i in range(60):\n    try:\n        c=boto3.client('s3',endpoint_url='%s',region_name='us-east-1',aws_access_key_id='k',"
                  "aws_secret_access_key='s'); c.create_bucket(Bucket='%s'); break\n    except Exception:\n        time.sleep(0.5)\nelse:\n    raise SystemExit(1)\n"
                  "c.put_bucket_versioning(Bucket='%s',VersioningConfiguration={'Status':'Enabled'})\n") % (endpoint, bucket, bucket)  # like B2
        made = docker("run", "--rm", "--network", "bridge", "--label", LABEL, "--entrypoint", "python", RUNNER, "-c", script, timeout=120)
        assert made.returncode == 0, made.stderr[-400:]
        yield {"endpoint": endpoint, "bucket": bucket}
    finally:
        docker("rm", "-f", name)


@pytest.fixture()
def offsite_volumes(volumes):
    suffix = uuid.uuid4().hex[:8]
    extra = {kind: f"napsedge-9b8b-{kind}-{suffix}" for kind in ("state", "recipients", "keys")}
    for name in extra.values():
        assert docker("volume", "create", "--label", LABEL, name).returncode == 0
    try:
        # the key pair, made by the IMAGE's own age-keygen; the identity stays in `keys`, which the backup container never mounts
        keygen = helper(["-v", f"{extra['keys']}:/k", "-v", f"{extra['recipients']}:/r"],
                        "umask 077 && age-keygen -o /k/identity.txt 2>/dev/null && age-keygen -y /k/identity.txt > /r/recipients.txt && chmod 0444 /r/recipients.txt "
                        "&& chown 10001:10001 /k/identity.txt")
        assert keygen.returncode == 0, keygen.stderr[-300:]
        assert helper(["-v", f"{extra['state']}:/s"], "chown 10001:10001 /s && chmod 0700 /s").returncode == 0
        for name, value in (("offsite-key-id", b"testing-key-id\n"), ("offsite-secret-key", f"testing-secret-{uuid.uuid4().hex}\n".encode())):
            assert helper(["-v", f"{volumes['cred']}:/v"], f"umask 077 && cat > /v/{name} && chown 10001:10001 /v/{name} && chmod 0400 /v/{name}", stdin=value).returncode == 0
        yield {**volumes, **extra}
    finally:
        for name in extra.values():
            docker("volume", "rm", "-f", name)


def test_a_the_built_image_stores_an_encrypted_verified_copy_and_it_is_recoverable_with_the_separate_key(case, offsite_volumes, emulator, tmp_path):
    v = offsite_volumes
    password = case.cluster.backup_url(case.database).password.encode()  # the harness's own synthetic backup password
    put_password(v, password + b"\n")
    env = job_env(case)
    env.pop("NAPSEDGE_BACKUP_ARTIFACT_ID")
    env.update({"NAPSEDGE_BACKUP_STATE_DIR": STATE_DIR, "NAPSEDGE_BACKUP_OFFSITE_ENABLED": "true", "NAPSEDGE_BACKUP_OFFSITE_ENDPOINT_URL": emulator["endpoint"],
                "NAPSEDGE_BACKUP_OFFSITE_ALLOW_HTTP_FOR_TESTS": "1", "NAPSEDGE_BACKUP_OFFSITE_REGION": "us-east-1", "NAPSEDGE_BACKUP_OFFSITE_BUCKET": emulator["bucket"],
                "NAPSEDGE_BACKUP_OFFSITE_PREFIX": "napsedge", "NAPSEDGE_BACKUP_OFFSITE_KEY_ID_FILE": f"{CRED_DIR}/offsite-key-id",
                "NAPSEDGE_BACKUP_OFFSITE_SECRET_KEY_FILE": f"{CRED_DIR}/offsite-secret-key", "NAPSEDGE_BACKUP_RECIPIENTS_FILE": f"{RECIPIENTS_DIR}/recipients.txt",
                "NAPSEDGE_BACKUP_UPLOAD_BACKOFF_SECONDS": "0", "NAPSEDGE_LOG_LEVEL": "WARNING"})
    argv = ["run", "--rm", "--read-only", "--user", "10001:10001", "--cap-drop", "ALL", "--security-opt", "no-new-privileges", "--network", "bridge",
            "--label", LABEL, "-v", f"{v['cred']}:{CRED_DIR}:ro", "-v", f"{v['ca']}:{CA_DIR}:ro", "-v", f"{v['recipients']}:{RECIPIENTS_DIR}:ro",
            "-v", f"{v['scratch']}:{SCRATCH_DIR}", "-v", f"{v['store']}:{STORE_DIR}", "-v", f"{v['state']}:{STATE_DIR}"]
    for key, value in env.items():
        argv += ["-e", f"{key}={value}"]
    argv += ["--entrypoint", "python", IMAGE, "-m", "src.deployment.entrypoints", "backup-cycle"]
    completed = docker(*argv, timeout=900)
    out = completed.stdout.decode().strip().splitlines()
    record = json.loads(out[-1])
    assert completed.returncode == 0, (record, completed.stderr[-600:])
    assert record["capture"]["report"]["outcome"] == "published" and record["offsite"]["outcome"] == "stored_verified" and record["states"]["remotely_stored"]
    assert password not in completed.stdout + completed.stderr and b"testing-secret" not in completed.stdout + completed.stderr
    assert not any("identity" in a or "/k:" in a for a in argv), "the backup container never sees the private key"
    assert helper(["-v", f"{v['scratch']}:/s:ro"], "ls -A /s").stdout.decode().strip() == "", "no plaintext tar, ciphertext or dump left"
    state = helper(["-v", f"{v['state']}:/s:ro"], "cat /s/cycles.jsonl; ls /s/offsite").stdout.decode()
    assert '"remotely_stored": true' in state and record["capture"]["report"]["artifact_id"] in state
    name = record["capture"]["report"]["artifact"]
    # retrieval on "another host": only the store, the separately held identity and the repository code
    script = ("import json,tempfile,os\nfrom src.deployment import backup_offsite as off\n"
              "store=off.S3ObjectStore(endpoint_url='%s',region='us-east-1',bucket='%s',key_id_file='/c/offsite-key-id',secret_key_file='/c/offsite-secret-key')\n"
              "d=tempfile.mkdtemp()\nf=off.fetch_artifact('%s',store=store,prefix='napsedge',age=off.AgeTool('/usr/bin/age'),identity_file='/k/identity.txt',destination=d)\n"
              "print(json.dumps({'valid':f.verdict.valid,'files':sorted(os.listdir(f.artifact_dir)),'artifact_id':f.record['artifact_id']}))\n") % (emulator["endpoint"], emulator["bucket"], name)
    fetched = docker("run", "--rm", "--network", "bridge", "--label", LABEL, "--user", "10001:10001", "--read-only", "--tmpfs", "/tmp:rw,mode=1777",
                     "-e", "PYTHONDONTWRITEBYTECODE=1", "-v", f"{v['keys']}:/k:ro", "-v", f"{v['cred']}:/c:ro", "--mount", f"type=bind,source={REPO},target=/repo,readonly",
                     "-w", "/repo", "--entrypoint", "python", IMAGE, "-c", script, timeout=300)
    assert fetched.returncode == 0, fetched.stderr.decode()[-800:]
    result = json.loads(fetched.stdout.decode().strip().splitlines()[-1])
    assert result == {"valid": True, "files": ["COMPLETE", "archive.dump", "baseline.json", "manifest.json"],
                      "artifact_id": record["capture"]["report"]["artifact_id"]}
